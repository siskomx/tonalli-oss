import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

// Copies verbatim license texts from the locked, locally installed packages.
// This maintenance command has no network access and is not a build-time fetch.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const lock = JSON.parse(fs.readFileSync(path.join(root, 'package-lock.json'), 'utf8'));
const retainedBuildPackages = [
  'react', 'react-dom', 'scheduler', 'react-router', 'react-router-dom',
  '@tanstack/react-query', '@tanstack/query-core',
  '@tanstack/react-virtual', '@tanstack/virtual-core',
  'cookie', 'set-cookie-parser', 'tailwindcss',
];
function dependencyKey(parent, name) {
  for (let directory = parent; ; directory = path.posix.dirname(directory)) {
    if (path.posix.basename(directory) !== 'node_modules') {
      const candidate = path.posix.join(directory, 'node_modules', name);
      if (lock.packages[candidate]) return candidate;
    }
    if (directory === '.') return null;
  }
}
// Map-library notices have their own asset bundle; add the chat dependency closure.
const pending = [...retainedBuildPackages, 'react-markdown', 'remark-gfm', '@tabler/icons-react', 'qrcode-generator', '@uppy/core', '@uppy/dashboard', '@uppy/react', '@uppy/locales', 'plyr', 'pdfjs-dist', 'three']
  .map((name) => dependencyKey('.', name));
const selected = new Set();
while (pending.length) {
  const key = pending.pop();
  if (!key) throw new Error('Missing locked UI dependency');
  if (selected.has(key)) continue;
  selected.add(key);
  const entry = lock.packages[key];
  for (const name of new Set([...Object.keys(entry.dependencies ?? {}), ...Object.keys(entry.peerDependencies ?? {}), ...Object.keys(entry.optionalDependencies ?? {})])) {
    // PDF.js's optional Node canvas backend is never part of the browser build.
    if (key === 'node_modules/pdfjs-dist' && name === '@napi-rs/canvas') continue;
    const child = dependencyKey(key, name);
    if (child) pending.push(child);
    else if (!entry.peerDependenciesMeta?.[name]?.optional && !Object.hasOwn(entry.optionalDependencies ?? {}, name)) {
      throw new Error(`Missing locked dependency ${name} of ${key}`);
    }
  }
}
const packages = [...selected].sort();
const sections = packages.flatMap((key) => {
  const entry = lock.packages[key];
  const directory = path.join(root, key);
  if (!fs.existsSync(directory) && entry.optional) return [];
  const installed = JSON.parse(fs.readFileSync(path.join(directory, 'package.json'), 'utf8'));
  const name = installed.name;
  if (installed.version !== entry.version) throw new Error(`Unlocked package: ${name}`);
  const licenses = fs.readdirSync(directory).filter((file) => /^(license|notice)(\..*)?$/i.test(file)).sort();
  let upstreamLicense;
  if (!licenses.length && name === '@uppy/components' && installed.version === '1.2.0') {
    // npm omits LICENSE; retain the root MIT text at this package's published gitHead.
    upstreamLicense = fs.readFileSync(path.resolve(root, '../third_party/uppy-components-1.2.0-LICENSE'));
    if (createHash('sha256').update(upstreamLicense).digest('hex') !== 'a0bceade78956c1954caa8dc9a8a665e78792ce94021baa15af72ffd6072b793') throw new Error('Uppy upstream license differs');
    licenses.push('upstream LICENSE');
  }
  if (!licenses.length && ({'mime-match':'1.0.2','murmurhash-js':'1.0.0','wildcard':'1.1.2'})[name] === installed.version) {
    const readme = fs.readFileSync(path.join(directory, 'README.md'), 'utf8');
    if (!readme.includes('Copyright (c)') || !readme.includes('Permission') || !readme.includes('SOFTWARE')) throw new Error(`Missing embedded license: ${name}`);
    licenses.push('README.md');
  }
  // This package carries its copyright/MIT notice in its source header.
  if (name === 'qrcode-generator' && installed.version === '1.4.4') {
    const source = fs.readFileSync(path.join(directory, 'qrcode.js'), 'utf8');
    if (!source.slice(0, 800).includes('Licensed under the MIT license:')) throw new Error('Missing QR source license');
    licenses.push('qrcode.js');
  }
  if (!licenses.length) throw new Error(`Missing license: ${name}`);
  return licenses.map((file) => {
    const bytes = upstreamLicense ?? fs.readFileSync(path.join(directory, file));
    const digest = createHash('sha256').update(bytes).digest('hex');
    const source = upstreamLicense ? 'https://github.com/transloadit/uppy/blob/9d87b9eab1f64c62f1708f5cec903def315c51e4/LICENSE' : entry.resolved;
    return `=== ${name} ${entry.version}: ${file} ===\nSource: ${source}\nOriginal SHA256: ${digest}\n\n${bytes.toString('utf8')}\n`;
  }).join('\n');
});
fs.writeFileSync(path.join(root, 'public/assets/react-ui-NOTICES.txt'),
  'Retained React UI dependency licenses\nGenerated by scripts/collect-ui-notices.mjs from package-lock.json and local node_modules.\nLicense text below is copied verbatim; package headers are Tonalli provenance metadata.\n\n' + sections.join('\n'), 'utf8');
console.log(`Retained license/notice texts for ${sections.length} locked packages.`);
const playerAssets=path.join(root,'public/assets/player');
fs.mkdirSync(playerAssets,{recursive:true});
fs.copyFileSync(path.join(root,'node_modules/plyr/dist/plyr.svg'),path.join(playerAssets,'plyr.svg'));

const pdfAssets=path.join(root,'public/assets/pdf');
fs.mkdirSync(pdfAssets,{recursive:true});
fs.copyFileSync(path.join(root,'node_modules/pdfjs-dist/build/pdf.worker.mjs'),path.join(pdfAssets,'pdf.worker.mjs'));
for(const name of ['cmaps','standard_fonts','iccs'])fs.cpSync(path.join(root,'node_modules/pdfjs-dist',name),path.join(pdfAssets,name),{recursive:true});
// No PDF scripting manager/QuickJS is used. Keep only image-decoder JS fallbacks.
const decoderAssets=path.join(pdfAssets,'decoders');fs.mkdirSync(decoderAssets,{recursive:true});
for(const name of fs.readdirSync(path.join(root,'node_modules/pdfjs-dist/wasm'))){
  if(name.endsWith('_nowasm_fallback.js')||name.startsWith('LICENSE_'))fs.copyFileSync(path.join(root,'node_modules/pdfjs-dist/wasm',name),path.join(decoderAssets,name));
}
const pdfNotices=[];
for(const directory of ['cmaps','standard_fonts','iccs','wasm']){
  for(const name of fs.readdirSync(path.join(root,'node_modules/pdfjs-dist',directory)).filter(name=>name.startsWith('LICENSE'))){
    const bytes=fs.readFileSync(path.join(root,'node_modules/pdfjs-dist',directory,name));
    pdfNotices.push(`=== pdfjs-dist 6.5.438 ${directory}/${name} ===\nOriginal SHA256: ${createHash('sha256').update(bytes).digest('hex')}\n\n${bytes.toString('utf8')}`);
  }
}
fs.writeFileSync(path.join(pdfAssets,'THIRD-PARTY-NOTICES.txt'),pdfNotices.join('\n\n'));

const upstreamRoot = path.resolve(root, '../third_party/project-nomad');
const upstream = JSON.parse(fs.readFileSync(path.join(upstreamRoot, 'UPSTREAM.json'), 'utf8'));
const license = fs.readFileSync(path.join(upstreamRoot, 'LICENSE'));
if (createHash('sha256').update(license).digest('hex') !== upstream.license_sha256) throw new Error('NOMAD license differs');
const changes = upstream.files.map((file) => `${file.destination}\n  Adapted from: ${file.original}`).join('\n');
fs.writeFileSync(path.join(root, 'public/assets/project-nomad-NOTICE.txt'),
  `Adapted Project NOMAD source\n${upstream.copyright}\nSource: ${upstream.repository}\nRevision: ${upstream.revision}\n`
  + `License: ${upstream.license}\nModified files and original paths:\n${changes}\n\nOriginal license text follows verbatim:\n\n`
  + license.toString('utf8'), 'utf8');
