"""Build original article fixtures with the pinned official Python libzim writer.

Run using the isolated libzim 4.1.0 environment; never synthesizes ZIM bytes.
"""
from __future__ import annotations

import hashlib
import json
import struct
from importlib.metadata import version
from pathlib import Path

from libzim.reader import Archive
from libzim.version import get_versions
from libzim.writer import Compression, Creator, Hint, Item, StringProvider

ROOT = Path(__file__).resolve().parents[1]
FIXTURES = ROOT / "crates/core/tests/fixtures/articles"
SOURCES = FIXTURES / "source"


class FixtureItem(Item):
    def __init__(self, path: str, title: str, mime: str, content: bytes):
        super().__init__()
        self.path, self.title, self.mime, self.content = path, title, mime, content

    def get_path(self):
        return self.path

    def get_title(self):
        return self.title

    def get_mimetype(self):
        return self.mime

    def get_contentprovider(self):
        return StringProvider(self.content)

    def get_hints(self):
        return {Hint.FRONT_ARTICLE: self.mime == "text/html", Hint.COMPRESS: False}


def build(kind: str, items: list[FixtureItem], redirects: list[tuple[str, str, str]]):
    path = FIXTURES / f"{kind}-v1.zim"
    if path.exists():
        path.unlink()
    with (
        Creator(path)
        .config_compression(Compression.none)
        .config_indexing(False, "eng")
        .config_nbworkers(1) as creator
    ):
        creator.set_mainpath(items[0].path)
        for name, value in {
            "Name": f"tonalli-article-{kind}-v1",
            "Title": f"Tonalli {kind} article fixture",
            "Description": "Original offline article and sandbox test content",
            "LongDescription": "Small original fixture generated by official libzim for Tonalli tests.",
            "Creator": "Tonalli contributors",
            "Publisher": "Tonalli contributors",
            "Language": "eng,spa",
            "Date": "2026-11-11",
        }.items():
            creator.add_metadata(name, value)
        for item in items:
            creator.add_item(item)
        for source, title, target in redirects:
            creator.add_redirection(source, title, target, {Hint.FRONT_ARTICLE: True})
    archive = Archive(path)
    checked = []
    for item in items:
        entry = archive.get_entry_by_path(item.path)
        content = bytes(entry.get_item().content)
        if content != item.content:
            raise RuntimeError(f"writer changed source bytes for {item.path}")
        checked.append({"path": item.path, "mime": item.mime, "bytes": len(content),
                        "sha256": hashlib.sha256(content).hexdigest()})
    for source, _, target in redirects:
        entry = archive.get_entry_by_path(source)
        if not entry.is_redirect or entry.get_redirect_entry().path != target:
            raise RuntimeError(f"writer redirect mismatch: {source}")
    raw = path.read_bytes()
    count = struct.unpack_from("<I", raw, 24)[0]
    pointers = struct.unpack_from("<Q", raw, 32)[0]
    canonical = {}
    for position in range(count):
        offset = struct.unpack_from("<Q", raw, pointers + position * 8)[0]
        redirect = struct.unpack_from("<H", raw, offset)[0] == 65535
        begin = offset + (12 if redirect else 16)
        end = raw.index(0, begin)
        writer_path = raw[begin:end].decode("utf-8")
        if raw[offset + 3] == ord("C"):
            canonical[writer_path] = "C/" + writer_path
    result = {"id": f"article-{kind}", "kind": kind,
            "path": str(path.relative_to(ROOT)).replace("\\", "/"),
            "bytes": path.stat().st_size,
            "sha256": hashlib.sha256(raw).hexdigest(),
            "uuid": raw[8:24].hex(), "md5": raw[-16:].hex(),
            "items": checked, "redirects": redirects, "urls": canonical}
    if hashlib.md5(raw[:-16]).digest() != raw[-16:]:
        raise RuntimeError("official writer archive MD5 mismatch")
    if kind == "benign":
        body = (SOURCES / "benign/assets/body-probe.bin").read_bytes()
        at = raw.find(body)
        if at < 0:
            raise RuntimeError("uncompressed body probe is not contiguous")
        result["body_probe"] = {"url": canonical["assets/body-probe.bin"],
                                "offset": at, "bytes": len(body),
                                "blocked_offset": at, "blocked_bytes": len(body)}
    return result


def item(kind: str, path: str, mime: str, title: str | None = None) -> FixtureItem:
    return FixtureItem(path, title or path, mime, (SOURCES / kind / path).read_bytes())


def main():
    package_version = version("libzim")
    native_versions = get_versions()
    if package_version != "4.1.0" or native_versions["libzim"] != "9.8.2":
        raise RuntimeError("use the verified libzim 4.1.0 wheel with native libzim 9.8.2")
    benign = [
        item("benign", "en/index.html", "text/html", "English fixture"),
        item("benign", "es/Niñez_y_educación.html", "text/html", "Niñez y educación"),
        item("benign", "assets/style.css", "text/css"),
        item("benign", "assets/pixel.png", "image/png"),
        item("benign", "assets/body-probe.bin", "application/octet-stream"),
    ]
    hostile = [item("hostile", f"hostile/{name}.html", "text/html")
               for name in ["passive", "all", "meta", "top", "popup", "form", "ping", "neutral"]]
    result = {"python_libzim": package_version, "native_versions": native_versions,
              "compression": "none", "indexing": False, "workers": 1,
              "packs": [build("benign", benign, [
                  ("redirect/start.html", "Redirect to English", "en/index.html"),
                  ("redirect/chain.html", "Redirect chain to English", "redirect/start.html"),
                  ("redirect/body-probe", "Redirect to body probe", "assets/body-probe.bin"),
              ]), build("hostile", hostile, [])]}
    text = json.dumps(result, ensure_ascii=False, indent=2) + "\n"
    # Native libzim also writes progress to stdout; keep machine metadata separate.
    (FIXTURES / "manifest.json").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
