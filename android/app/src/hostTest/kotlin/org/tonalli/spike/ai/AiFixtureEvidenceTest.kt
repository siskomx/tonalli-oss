package org.tonalli.spike.ai

fun fixtureEvidenceTests() {
    val evidence = AiFixtureEvidence("abc", "hello", "abc", 128u)
    val initial = evidence.snapshot()
    check(initial.questionSha256 == "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad")
    check(initial.contextSha256 == "2cf24dba5fb0a30e26e83b2ac5b9e29e1b161e5c1fa7425e73043362938b9824")
    check(initial.promptSha256 == initial.questionSha256 && initial.outputCap == 128u)
    check(initial.terminal == null && !initial.comparisonEligible && initial.chunks.isEmpty())
    evidence.started(4uL, 5L)
    evidence.text(4uL, 7L, "<think>raw control tags</think>")
    val beforeMore = evidence.snapshot()
    evidence.text(4uL, 11L, "\nRespuesta: ñ.")
    check(beforeMore.chunks.size == 1) { "Published snapshot mutated after a later callback" }
    val live = evidence.snapshot()
    check(live.chunks.map { it.text }.joinToString("") == "<think>raw control tags</think>\nRespuesta: ñ.")
    check(live.firstRawNs == 7L && live.firstUsefulAnswerNs == null)
    check(live.started == AiFixtureEvidence.Started(4uL, 5L))
    check(live.chunks.map { it.receivedNs } == listOf(7L, 11L))
    val stats = mutableMapOf("input_tokens" to "128", "output_tokens" to "12")
    check(evidence.terminal("Eos", false, false, stats))
    stats["output_tokens"] = "999"
    val done = evidence.snapshot()
    check(done.comparisonEligible && done.terminal?.stats?.get("output_tokens") == "12")
    check(!evidence.terminal("Error", true, false, emptyMap()))
    check(evidence.snapshot().terminal?.reason == "Eos")

    val bounded = AiFixtureEvidence("abc", "hello", "abc", 32u, maxChunks = 2, maxBytes = 4)
    bounded.text(1uL, 1L, "é")
    bounded.text(1uL, 2L, "é")
    bounded.text(1uL, 3L, "x")
    bounded.terminal("MaxTokens", false, false, emptyMap())
    val lost = bounded.snapshot()
    check(lost.chunks.map { it.text }.joinToString("") == "éé")
    check(lost.omittedChunks == 1L && !lost.comparisonEligible)
    val byteBound = AiFixtureEvidence("abc", "hello", "abc", 32u, maxChunks = 10, maxBytes = 1)
    byteBound.text(1uL, 1L, "é")
    check(byteBound.snapshot().omittedChunks == 1L && byteBound.snapshot().chunks.isEmpty())

    val cancelled = AiFixtureEvidence("abc", "hello", "abc", 32u)
    cancelled.cancellationRequested()
    check(cancelled.snapshot().terminal == null && !cancelled.snapshot().comparisonEligible)
    check(cancelled.snapshot().cancellationRequested)
    cancelled.terminal("Cancelled", false, true, emptyMap())
    check(!cancelled.snapshot().comparisonEligible)
    val error = AiFixtureEvidence("abc", "hello", "abc", 32u)
    error.text(1uL, 1L, "Partial output")
    error.terminal("Error", true, false, emptyMap())
    check(error.snapshot().chunks.single().text == "Partial output" && !error.snapshot().comparisonEligible)
    println("PASS: exact fixture hashes, immutable raw control tags/timestamps, bounded omissions and honest cancellation/incomplete/error evidence")
}
